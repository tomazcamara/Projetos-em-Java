package projetos.java.tomaz.conceito;

public class Array02 {
    static void main(String[] args) {
        String[] nome = new String[3];
        nome[0] = "Tomaz";
        nome[1] = "Miguel";
        nome[2] = "Lucas";
        for (int i = 0; i < nome.length ; i++) {
            System.out.println(nome[i]);

        }

    }
}
